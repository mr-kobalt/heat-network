package ru.lct.heating.config;

/**
 * Политика выбора финального прямого вывода к точке подключения ОКС (ADR-0024).
 */
public enum OksApproachPolicy {

    /**
     * Ближайшая допустимая внешняя грань: перпендикуляр к проекции точки на ребро.
     * Среди допустимых (выход вне буферов всех ограничений) выбирается ближайшее
     * ребро. Если перпендикуляр недопустим — кратчайший прямой выход из кармана.
     */
    PERPENDICULAR_NEAREST,

    /**
     * Буквальное ТП 2.2: сначала направление на ближайшую точку контура (включая
     * вершину); если вывод недопустим — переход к
     * {@link #PERPENDICULAR_NEAREST}.
     */
    NEAREST_BOUNDARY
}
