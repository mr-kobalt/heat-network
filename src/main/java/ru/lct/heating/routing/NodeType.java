package ru.lct.heating.routing;

/**
 * Тип узла плана новой сети (ТП v2). Присоединение выполняется через тепловую
 * камеру; отдельного узла `tie_in` нет (FR-33).
 */
public enum NodeType {
    /** Тепловая камера (существующая или новая); точка присоединения/ветвления. */
    CHAMBER,
    /** Технический узел — смена параметра без разветвления. */
    TECHNICAL_NODE,
    /** Точка подключения перспективного ОКС. */
    CONNECTION_POINT
}
